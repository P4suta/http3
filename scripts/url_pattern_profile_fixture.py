def encoded(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def build():
    cases = []
    def add(name, kind, requirements, steps, **fields):
        cases.append(dict(id=name, kind=kind, requirements=requirements,
                          steps=steps, **fields))
    def parse(name, text, expected, req, steps):
        add(name, 'constructor', req, steps, input=text, expected=expected)
    parse('initial-empty', '', {'pathname': ''}, ['P04'], ['initial-eof-rewind'])
    parse('initial-relative', 'file', {'pathname': 'file'}, ['P04'], ['initial-eof-rewind'])
    parse('host-eof', 'https://example.com', {'protocol':'https','hostname':'example.com','port':''}, ['P04'], ['protocol-authority','host-eof'])
    parse('host-query', 'https://example.com?q', {'protocol':'https','hostname':'example.com','port':'','pathname':'/','search':'q'}, ['P04','P06'], ['protocol-authority','pathname-search-hash'])
    parse('credentials', r'https://u\:p@example.com:8443/p?q#h', {'protocol':'https','username':'u','password':'p','hostname':'example.com','port':'8443','pathname':'/p','search':'q','hash':'h'}, ['P05','P06'], ['username-password','port-end','pathname-search-hash'])
    parse('credentials-empty', 'https://@example.com:', {'protocol':'https','username':'','hostname':'example.com','port':''}, ['P05'], ['username-password','port-end'])
    parse('password-repeated-at', r'https://u\:p@q@example.com/p', {'protocol':'https','username':'u','password':'p','hostname':'q@example.com','port':'','pathname':'/p'}, ['P05'], ['username-password'])
    parse('ipv6-brackets', r'https://[\:\:1]:8443/p', {'protocol':'https','hostname':r'[\:\:1]','port':'8443','pathname':'/p'}, ['P05'], ['ipv6-brackets','port-end'])
    parse('search-only', '?q#h', {'search':'q','hash':'h'}, ['P06'], ['pathname-search-hash'])
    parse('hash-only', '#h', {'hash':'h'}, ['P06'], ['pathname-search-hash'])
    parse('group-delimiter', '/{a?b}/tail#h', {'pathname':'/{a?b}/tail','search':'','hash':'h'}, ['P06'], ['group-boundary'])
    parse('optional-name', '/:file?query#h', {'pathname':'/:file?query','search':'','hash':'h'}, ['P06'], ['optional-modifier'])
    parse('escaped-scheme', r'https\://example.com/p', {'protocol':'https','hostname':'example.com','port':'','pathname':'/p'}, ['P04','P07'], ['protocol-authority','lenient-delimiter'])

    for option, separator, prefix in [('path',47,47),('hostname',46,-1),('generic',-1,-1)]:
        for part, token in [('literal','{a}'),('segment','{:x}'),('full','{(.*)}')]:
            for modifier in ['', '?', '+', '*']:
                for index, value in enumerate(['','a','aa','a/b','a.b']):
                    if part == 'literal':
                        matched = (value == 'a' if modifier == '' else
                                   value in ('','a') if modifier == '?' else
                                   bool(value) and set(value) == {'a'} if modifier == '+' else
                                   not value or set(value) == {'a'})
                    elif part == 'segment':
                        matched = (bool(value) or modifier in ('?','*')) and (separator < 0 or chr(separator) not in value)
                    else:
                        matched = True
                    add(f'primitive-{option}-{part}-{modifier or "none"}-{index}', 'component',
                        ['P08','P09'], ['part-modifier-options','finite-primitive-language'],
                        pattern=token+modifier, input=value, separator=separator, prefix=prefix,
                        expected='matched' if matched else 'not_matched')
    for name, value, matched in [('empty','',True),('one','pA-q',True),('two','pA-qpB-q',True),('bad','pA',False)]:
        add('prefix-suffix-'+name, 'component', ['P09'], ['prefix-suffix-repetition'],
            pattern='{p:x-q}*', input=value, separator=47, prefix=47,
            expected='matched' if matched else 'not_matched')
    for name, pattern in [('dangling-escape','\\'),('missing-name',':'),('arbitrary-regexp','(a|b)'),('duplicate-name',':a/:a')]:
        req,steps=(['P08'],['duplicate-name']) if name=='duplicate-name' else (['P01','P07'],['has-regexp-refusal','strict-invalid']) if name=='arbitrary-regexp' else (['P07'],['strict-invalid'])
        add('invalid-'+name,'component',req,steps,
            pattern=pattern,input='a',separator=47,prefix=47,expected='invalid_pattern')
    add('unicode-name','component',['P07'],['unicode-name'],pattern=':é',input='value',separator=47,prefix=47,expected='matched')

    def enc(name, kind, value, expected, req, steps):
        add(name,'encoding',req,steps,encoding=kind,input=value,expected=expected)
    for name,value,expected in [('lower','HTTPS','https'),('empty','',''),('tabs','ht\ttps','https'),('invalid','1https',None)]:
        steps=['empty-scheme'] if name=='empty' else ['tab-preprocess','ascii-scheme'] if name=='tabs' else ['ascii-scheme']
        enc('scheme-'+name,'protocol',value,expected,['P13'],steps)
    enc('userinfo','userinfo','a:b@c /é','a%3Ab%40c%20%2F%C3%A9',['P14'],['userinfo-encode-set','utf8-bytes'])
    for name,value,expected in [('zero','00443','443'),('prefix','80abc','80'),('max','65535','65535'),('overflow','65536',None),('empty','','')]:
        enc('port-'+name,'port',value,expected,['P12'],['port-only-no-default'] if name=='empty' else ['port-only-no-default','numeric-prefix'])
    enc('ipv6-piece','ipv6_pattern','[ABCD:','[abcd:',['P16'],['ascii-fixed-piece','not-full-ipv6-parse'])
    enc('ipv6-invalid','ipv6_pattern','.1]',None,['P16'],['ascii-fixed-piece'])
    for name,value,expected in [('dots','a/../b é','a/../b %C3%A9'),('query','a?b','a'),('hash','a#b','a'),('space-before-hash','a #b','a%20'),('terminal-space','a ','a ')]:
        steps=['preserve-dots'] if name=='dots' else ['terminal-space'] if name=='terminal-space' else ['query-fragment-transition']
        enc('opaque-'+name,'opaque_path',value,expected,['P18'],steps)
    enc('query-encode','search',"a b'`?#é",'a%20b%27`?%23%C3%A9',['P19'],['special-query-apostrophe'])
    enc('hash-encode','hash',"a b'`?#é","a%20b'%60?#%C3%A9",['P19'],['hash-encode-set'])

    def full(name, pattern, candidate, expected, req, steps, base='https://example.com/dir/base?old#before'):
        add(name,'full',req,steps,pattern=pattern,base=base,candidate=candidate,expected=expected)
    for scheme in ['ftp','file','http','https','ws','wss']:
        # Constructor raw state is observable even where candidate URLs are outside HTTP(S).
        parse('special-'+scheme, scheme+'\\:example.com#h', {'protocol':scheme,'hostname':'example.com','port':'','pathname':'/','search':'','hash':'h'}, ['P02'], ['six-special-schemes'])
    parse('special-optional','https{x}?\\:example.com#h',{'protocol':'https{x}?','hostname':'example.com','port':'','pathname':'/','search':'','hash':'h'},['P02'],['optional-pattern'])
    parse('opaque-selection','data\\:opaque?q',{'protocol':'data','hostname':'','port':'','pathname':'opaque','search':'q'},['P02'],['opaque-selection'])
    for i, host in enumerate([r'[\:\:1]',r'{[\:\:1]}',r'\[\:\:1]']):
        full('ipv6-prefix-'+str(i),'https://'+host+'/*','https://[::1]/a','matched',['P03'],['three-prefixes'])
    # The constructor skips group contents before its bracket-depth handling.
    # Bracketing only '[' therefore does not protect the following colons.
    full('ipv6-split-group',r'https://{[}\:\:1]/*','https://[::1]/a','invalid_pattern',['P03','P06'],['three-prefixes','group-boundary'])
    for i,path in enumerate(['/file',r'\/file','{/file}']):
        full('absolute-'+str(i),path,'https://example.com/file','matched',['P03'],['absolute-pathname'])
    full('base-escape','file','https://example.com/a*/(fixed)/file','matched',['P11'],['escape-base','relative-directory'],base='https://example.com/a*/(fixed)/base')
    full('base-escape-negative','file','https://example.com/anything/(fixed)/file','not_matched',['P11'],['escape-base'],base='https://example.com/a*/(fixed)/base')
    full('base-hash','#new','https://example.com/dir/base?old#new','matched',['P11'],['inherit-prefix'])
    for name,scheme,port,expected in [('literal','https','443','matched'),('group-scheme','{https}','443','not_matched'),('case-scheme','HTTPS','443','not_matched'),('group-port','https','{443}','not_matched')]:
        full('default-'+name,scheme+'://example.com:'+port+'/*','https://example.com/a',expected,['P12'],['default-before-encoding'])
    for name,hostname,expected in [('slash','{example.com/ignored}','matched'),('empty-slash','{/ignored}','invalid_pattern'),('empty-query',r'{\?ignored}','invalid_pattern'),('empty-hash','{#ignored}','invalid_pattern')]:
        full('hostname-'+name,'https://'+hostname+'/*','https://example.com/a',expected,['P15'],['nonempty-prefix'] if name=='slash' else ['empty-prefix-rejection'])
    add('complete-host-delimiter','host',['P15'],['complete-host-distinct'],input='example.com/ignored',expected=None)
    add('complete-host-normal','host',['P15'],['complete-host-distinct'],input='EXAMPLE.COM',expected='example.com')
    full('fixed-merge','https://{127}.0.0.1/*','https://127.0.0.1/a','matched',['P08'],['fixed-merge'])
    full('fixed-dot','/a/{..}/b','https://example.com/b','matched',['P17'],['fixed-dot-merge'])
    full('variable-dot','/:x/../b','https://example.com/b','not_matched',['P17'],['variable-boundary'])
    full('canonical-ipv6-domain',r'https://[\:\:1]/*','https://example.com/a','not_matched',['P20'],['canonical-input-no-callback'])
    full('case-sensitive','/Upper','https://example.com/upper','not_matched',['P20'],['case-sensitive-result'])
    full('create-match','https://example.com/*','https://example.com/a','matched',['P01'],['string-create','boolean-match'])

    for name,operation,amount in [('negative-compile','compile',-1),('zero-compile','compile',0),('positive-compile','compile',8388608),('negative-match','match',-1),('zero-match','match',0),('positive-match','match',8388608)]:
        steps=['finite-'+operation+'-credit']+(['negative-credit'] if amount<0 else [])
        add('budget-'+name,'budget',['P22'],steps,operation=operation,amount=amount,expected='ok' if amount>0 else 'work_limit_exceeded')
    for name,operation,count,expected in [('authored-at','authored',2048,'ok'),('authored-over','authored',2049,'work_limit_exceeded'),('derived-at','derived',16383,'ok'),('derived-graph-over','derived',16384,'work_limit_exceeded'),('encoding-at','encoding',8192,'ok'),('encoding-over','encoding',8193,'work_limit_exceeded'),('encoding-expanded','expanded',2731,'work_limit_exceeded'),('candidate-at','candidate',8192,'ok'),('candidate-over','candidate',8193,'work_limit_exceeded')]:
        add('budget-'+name,'budget',['P22'],['byte-and-state-admission'],operation=operation,amount=count,expected=expected)
    rules = []
    for ident, authority, anchor, steps, coverage in POLICY:
        checks=[c['id'] for c in cases if ident in c['requirements']]
        rules.append(dict(id=ident,authority=authority,anchor=anchor,steps=steps,coverage=coverage,checks=checks))
    bound_sources=['scripts/url_pattern_profile_fixture.py','scripts/urlpattern_full_reference.py',
                   'scripts/urlpattern_reference.mjs','scripts/url_host_tables.py',
                   'src/http/internal/url_pattern/unicode.gleam','src/http/internal/url_pattern/host_data.gleam']
    source_hashes={p:hashlib.sha256((ROOT/p).read_bytes()).hexdigest() for p in bound_sources}
    profile=dict(schema=1,scope='rfc9842-string-boolean-bounded-profile',pins=PINS,
                 source_hashes=source_hashes,
                 specification_sha256={'urlpattern':'e93fd5310a762a3835f256aa6c1b076634f57c1ef5bd170fb9a8ffabc7fea936',
                                       'callbacks':'f2392c3bad5ccb3b253cfcebdb98f16abb12c4669c578396dd7ab518957a9d87',
                                       'url':'8e2eef304c23375141e1ac38268d5b5a54eff934c14c3175b323aab419b0dfbe'},
                 requirements=rules,case_count=len(cases),
                 capability_boundary=[
                     'rfc9842-string-pattern-create-match-and-regexp-refusal',
                     'unicode-data-pinned-to-16.0.0',
                     'automatic-http-cdt-not-integrated',
                 ],
                 hostname_reference_disagreements=[8,10,11])
    return profile,dict(schema=1,cases=cases)


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--write',action='store_true');parser.add_argument('--check',action='store_true')
    args=parser.parse_args();assert args.write != args.check
    profile,cases=build()
    reference=json.loads((ROOT/'test/fixtures/urlpattern-full-independent.json').read_bytes())
    def canonical(value):
        return json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':')).encode()
    policy={'profile':{k:v for k,v in profile.items() if k!='requirements'},
            'requirements':[{k:v for k,v in row.items() if k!='checks'} for row in profile['requirements']],
            'reference':{k:v for k,v in reference.items() if k!='cases'},
            'reference_cases_sha256':hashlib.sha256(canonical(reference['cases'])).hexdigest(),
            'matrix_sha256':hashlib.sha256(canonical(cases)).hexdigest()}
    policy_literal=json.dumps(canonical(policy).decode(),ensure_ascii=True)
    policy_header=('%% Generated by scripts/url_pattern_profile_fixture.py; reviewed finite policy.\n'
                   'upp_policy() -> json:decode(<<'+policy_literal+'>>).\n').encode()
    outputs=[('test/fixtures/urlpattern-profile.json',encoded(profile)),
             ('test/fixtures/urlpattern-profile-cases.json',encoded(cases)),
             ('test/url_pattern_profile_policy.hrl',policy_header)]
    for relative,data in outputs:
        path=ROOT/relative
        if args.write:path.write_bytes(data)
        else:assert path.read_bytes()==data
    print(json.dumps({'profile_rows':23,'cases':len(cases['cases']),'qualification':False}))


if __name__=='__main__':main()
